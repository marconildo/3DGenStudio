// Regenerates db/names.js — the lookup tables the PostgreSQL driver needs in
// order to hand storage.js rows in the shape it already expects.
//
// WHY THIS EXISTS
// ---------------
// PostgreSQL folds unquoted identifiers to lower case. The schema is camelCase
// throughout (filePath, kanbanColumnId, creationDate), so `SELECT filePath FROM
// Assets` still matches — Postgres lower-cases both sides — but the row comes
// back keyed `filepath`, and every `row.filePath` in storage.js silently reads
// undefined. Silent wrongness is the failure mode this codebase can least
// afford, so db/postgres.js renames the keys on the way out and this file is the
// map it uses.
//
// The alternative — quoting every identifier in the DDL — would force all ~318
// queries to quote as well, or nothing would match at all.
//
// Run after adding a column, or a new `AS alias` to a query:
//   node tools/gen-db-names.mjs
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'storage.js');
const TARGET = path.join(ROOT, 'db', 'names.js');

const sql = fs.readFileSync(SOURCE, 'utf8');

// One pass over every CREATE TABLE body, feeding both outputs below.
const tableBodies = [...sql.matchAll(/CREATE TABLE(?: IF NOT EXISTS)? (\w+) \(([\s\S]*?)\n\s*\);/g)];

const names = new Set();

// 1. Column names declared in CREATE TABLE bodies. Requiring a type keyword is
//    what separates a column line from a constraint line — PRIMARY KEY(...),
//    FOREIGN KEY(...) and UNIQUE(...) all start with a keyword instead.
for (const [, , body] of tableBodies) {
  for (const line of body.split('\n')) {
    const col = line.match(/^\s*([A-Za-z_]\w*)\s+(INTEGER|BIGINT|TEXT|REAL|BLOB|NUMERIC)\b/i);
    if (col) names.add(col[1]);
  }
}

// 2. Columns bolted on later by the idempotent add-if-missing migrations, which
//    never appear in a CREATE TABLE body. Both spellings are matched: the
//    literal ALTER TABLE, and the addColumnIfMissing(table, column, type) helper
//    that most of them go through.
//
//    This is not hypothetical tidiness. Moving those probes onto the helper
//    dropped `graphViewport` out of the dictionary, which would have made
//    Projects.graphViewport read as undefined on PostgreSQL — the exact silent
//    failure this file exists to prevent.
for (const m of sql.matchAll(/ALTER TABLE \w+ ADD COLUMN ([A-Za-z_]\w*)/g)) {
  names.add(m[1]);
}
for (const m of sql.matchAll(/addColumnIfMissing\(\s*'[^']+'\s*,\s*'([A-Za-z_]\w*)'/g)) {
  names.add(m[1]);
}

// 3. Result aliases. These are not columns anywhere, but they are read off rows
//    just the same: assetFilePath, kanbanColumnName, nextPosition, ...
//
//    CAST(? AS BIGINT) uses the same keyword, so the type name has to be
//    rejected — otherwise BIGINT lands in the dictionary as though it were a
//    column. Every real alias in this codebase is camelCase, and no SQL type
//    name is, so requiring a lower-case letter separates them cleanly.
for (const m of sql.matchAll(/\bAS\s+([A-Za-z_]\w*)/g)) {
  if (/[a-z]/.test(m[1])) names.add(m[1]);
}

// Only mixed-case names need mapping. An already-lower-case key survives the
// round trip untouched, so including it would be noise.
const camel = [...names].filter(name => name !== name.toLowerCase()).sort();

// A collision would make the map ambiguous and silently resolve to one of the
// two — precisely the class of bug this whole mechanism exists to prevent.
const seen = new Map();
const collisions = [];
for (const name of camel) {
  const key = name.toLowerCase();
  if (seen.has(key)) collisions.push(`${seen.get(key)} / ${name}`);
  else seen.set(key, name);
}
if (collisions.length) {
  console.error('FATAL: these names collide when lower-cased:', collisions.join(', '));
  process.exit(1);
}

// Which tables carry a plain `id` primary key. The PostgreSQL driver appends
// RETURNING id to an INSERT to reproduce node-sqlite3's lastID, and doing that
// against a join table keyed (cardId, assetId) is a hard error, not a no-op.
// Deduplicated: Cards and Connections each appear twice, because the one-time
// Nodes->Cards migration builds its own copy before the main schema block runs.
const tablesWithId = [...new Set(
  tableBodies
    .filter(([, , body]) => /^\s*id\s+(INTEGER|BIGINT)\b/im.test(body))
    .map(([, table]) => table.toLowerCase())
)].sort();

const keyLines = camel
  .map(name => `  ${JSON.stringify(name.toLowerCase())}: ${JSON.stringify(name)}`)
  .join(',\n');
const tableLines = tablesWithId.map(table => `  ${JSON.stringify(table)}`).join(',\n');

const output = `// GENERATED by tools/gen-db-names.mjs — do not hand-edit.
//
// Regenerate after adding a column or a new "AS alias" to a query:
//   node tools/gen-db-names.mjs

// Lower case -> the camelCase key storage.js actually reads. PostgreSQL folds
// unquoted identifiers to lower case, so every row it returns is keyed in lower
// case; db/postgres.js renames them through this map before storage.js sees
// them. Names that are already lower case are absent on purpose — they need no
// mapping, and listing them would only invite drift.
export const CANONICAL_KEYS = Object.freeze({
${keyLines}
});

// Tables whose primary key is a single \`id\` column, lower-cased because that is
// how PostgreSQL stores the table name and how the driver looks it up. Anything
// absent here is keyed by a composite or a foreign id, and must never have
// RETURNING id appended to its inserts.
export const TABLES_WITH_ID = Object.freeze(new Set([
${tableLines}
]));
`;

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, output);
console.log(
  `db/names.js: ${camel.length} camelCase names, ${tablesWithId.length} tables with an id column, no collisions`
);
