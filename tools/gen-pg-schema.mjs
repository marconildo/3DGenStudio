// Regenerates db/schema.pg.sql from the SQLite schema in storage.js.
//
// WHY GENERATE RATHER THAN HAND-WRITE
// -----------------------------------
// Two schemas that are meant to be identical, maintained by hand, drift — and a
// column present on one engine and missing on the other fails at runtime, on
// whichever deployment nobody tested. storage.js stays the single source of
// truth; this script translates it.
//
// IDENTIFIER CASE IS LOAD-BEARING. Everything is emitted UNQUOTED, so PostgreSQL
// folds it to lower case. That is deliberate: storage.js queries say
// `SELECT filePath FROM Assets`, Postgres lower-cases both sides, and they match.
// Quoting the DDL as "filePath" would break every one of those ~318 queries at
// once. The returned rows come back lower-cased, which db/postgres.js maps back
// through db/names.js.
//
// Run after changing the schema:
//   node tools/gen-pg-schema.mjs
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'storage.js');
const TARGET = path.join(ROOT, 'db', 'schema.pg.sql');

const source = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');

// Only the CREATE TABLE IF NOT EXISTS statements from the live schema block. The
// legacy Nodes->Cards migration builds its own bare `CREATE TABLE Cards (...)`,
// which is SQLite-only history and must not reach PostgreSQL: a Postgres
// database is always either created fresh from this file or filled by the
// migration tool, so it can never be in a pre-Cards state.
const tables = [...source.matchAll(/CREATE TABLE IF NOT EXISTS (\w+) \(([\s\S]*?)\n    \);/g)];
if (tables.length < 15) {
  console.error(`FATAL: found only ${tables.length} tables — the DDL shape changed`);
  process.exit(1);
}

const indexes = [...source.matchAll(/'(CREATE INDEX IF NOT EXISTS [^']+)'/g)].map(m => m[1]);
if (!indexes.length) {
  console.error('FATAL: no CREATE INDEX statements found');
  process.exit(1);
}

function translateColumn(line) {
  let out = line;

  // AUTOINCREMENT -> an identity column. BY DEFAULT rather than ALWAYS, because
  // importProjectExport and the SQLite->PostgreSQL migration both insert
  // explicit ids, which ALWAYS would reject outright.
  out = out.replace(
    /\bINTEGER PRIMARY KEY AUTOINCREMENT\b/,
    'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  );

  // Every remaining INTEGER becomes BIGINT. Not cosmetic: project ids are
  // allocated as Date.now() (~1.8e12) and every timestamp column holds
  // milliseconds, both of which overflow PostgreSQL's 4-byte INTEGER. Applying
  // it uniformly also keeps each foreign key the same width as the id it
  // references, which Postgres requires for an index to be usable.
  out = out.replace(/\bINTEGER\b/g, 'BIGINT');

  // SQLite REAL is a 64-bit float.
  out = out.replace(/\bREAL\b/g, 'DOUBLE PRECISION');

  // No such collation in PostgreSQL. Case-insensitive uniqueness is restored
  // below by a unique index on lower(login), and the queries that relied on the
  // collation now say lower() explicitly.
  out = out.replace(/ COLLATE NOCASE/g, '');

  // INITIALLY IMMEDIATE means normal operation is unchanged — every foreign key
  // is still checked per statement, exactly as on SQLite. What DEFERRABLE buys is
  // the ability to say SET CONSTRAINTS ALL DEFERRED inside one transaction, which
  // is how tools/migrate-sqlite-to-postgres.mjs loads whole tables at a time
  // without having to work out an insertion order for self-referencing rows
  // (Assets.parentId, WikiPages.parentId).
  if (/FOREIGN KEY\s*\(.*REFERENCES/i.test(out)) {
    out = out.replace(/(\s*)(,?)$/, ' DEFERRABLE INITIALLY IMMEDIATE$2');
  }

  return out;
}

// SQLite resolves foreign keys lazily, so storage.js can declare Cards ->
// NodeTypes before NodeTypes exists. PostgreSQL resolves them at CREATE time and
// errors out, so the tables have to be emitted dependency-first.
function sortByDependency(entries) {
  const bodyByTable = new Map(entries.map(([, table, body]) => [table, body]));
  const ordered = [];
  const done = new Set();
  const visiting = new Set();

  const visit = (table) => {
    if (done.has(table)) return;
    if (visiting.has(table)) {
      // Only a cycle between *different* tables is unresolvable; a self
      // reference (Assets.parentId, WikiPages.parentId) is fine and is filtered
      // out below before we ever get here.
      console.error(`FATAL: circular foreign keys involving ${table}`);
      process.exit(1);
    }
    visiting.add(table);

    const body = bodyByTable.get(table) ?? '';
    for (const ref of body.matchAll(/REFERENCES\s+(\w+)\s*\(/g)) {
      const target = ref[1];
      if (target !== table && bodyByTable.has(target)) visit(target);
    }

    visiting.delete(table);
    done.add(table);
    ordered.push(table);
  };

  for (const [, table] of entries) visit(table);
  return ordered.map(table => entries.find(([, name]) => name === table));
}

const statements = [];

for (const [, table, body] of sortByDependency(tables)) {
  const lines = body.split('\n').map(translateColumn);
  statements.push(`CREATE TABLE IF NOT EXISTS ${table} (${lines.join('\n')}\n);`);
}

// Columns that storage.js adds after the fact via addColumnIfMissing. Most are
// also declared in a CREATE TABLE body, but not all — Projects.graphViewport
// exists ONLY as one of these. Leaving them out produced a schema that looked
// complete and silently dropped that column during migration, so they are
// emitted here rather than relied upon to appear above.
const addedColumns = [...source.matchAll(
  /addColumnIfMissing\(\s*'(\w+)'\s*,\s*'(\w+)'\s*,\s*'([^']+)'\s*\)/g
)];
if (!addedColumns.length) {
  console.error('FATAL: no addColumnIfMissing calls found — did that helper get renamed?');
  process.exit(1);
}
for (const [, table, column, type] of addedColumns) {
  const pgType = type.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bREAL\b/g, 'DOUBLE PRECISION');
  statements.push(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${column} ${pgType};`);
}

for (const index of indexes) {
  statements.push(`${index};`);
}

// Restores what COLLATE NOCASE guaranteed on SQLite: two logins differing only
// in case cannot both exist. Also makes findUserByLogin's lower(login) lookup an
// index scan rather than a sequential one.
statements.push(
  'CREATE UNIQUE INDEX IF NOT EXISTS users_login_lower_key ON Users (lower(login));'
);

const header = `-- GENERATED by tools/gen-pg-schema.mjs from the schema in storage.js.
-- Do not hand-edit: change storage.js and regenerate, or the two engines drift.
--
-- Identifiers are deliberately UNQUOTED. PostgreSQL folds them to lower case,
-- which is exactly what lets storage.js keep its camelCase queries unchanged --
-- \`SELECT filePath FROM Assets\` lower-cases on both sides and matches. Rows come
-- back lower-cased and db/postgres.js maps the keys back via db/names.js.
--
-- The one-time legacy migrations in storage.js (Nodes->Cards, Assets_Edits) are
-- NOT represented here and never run against PostgreSQL: a Postgres database is
-- either created fresh from this file or populated by
-- tools/migrate-sqlite-to-postgres.mjs, so it cannot be in a pre-migration state.

`;

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, header + statements.join('\n\n') + '\n');

console.log(`db/schema.pg.sql: ${tables.length} tables, ${indexes.length + 1} indexes`);

// A leftover SQLite-ism reaching Postgres would fail at CREATE time on a fresh
// deployment, which is the worst place to find out.
const emitted = fs.readFileSync(TARGET, 'utf8');
const ddlOnly = emitted
  .split('\n')
  .filter(line => !line.trim().startsWith('--'))
  .join('\n');
const leftovers = ['AUTOINCREMENT', 'COLLATE NOCASE', 'PRAGMA', ' REAL ', ' INTEGER '].filter(token =>
  ddlOnly.includes(token)
);
if (leftovers.length) {
  console.error('FATAL: untranslated SQLite syntax in the output:', leftovers.join(', '));
  process.exit(1);
}
